import argparse
import glob
import os
import re

try:
    from docx import Document
    from docx.shared import Inches
except ImportError:
    print("Error: The 'python-docx' library is missing. Please run 'pip install python-docx' in your terminal.")
    exit()

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))

def parse_args():
    parser = argparse.ArgumentParser(description="Compile generated profile images into a Word appendix.")
    parser.add_argument(
        "--base-folder",
        default=os.environ.get("SAFR_BASE_FOLDER", SCRIPT_DIR),
        help="Root folder to search recursively for profile images.",
    )
    parser.add_argument(
        "--output-file",
        default=os.environ.get("SAFR_APPENDIX_OUTPUT_FILE", "SAFR_Visual_Appendix.docx"),
        help="Output .docx file path.",
    )
    return parser.parse_args()

# -------------------------------------------------------------------------
# 1. SETUP & FILE GATHERING
# -------------------------------------------------------------------------
args = parse_args()
base_folder = args.base_folder
output_file = args.output_file

# Search recursively for all PNG files generated by your scripts
all_images = glob.glob(os.path.join(base_folder, "**", "*.png"), recursive=True)

# Filter to ensure we only grab the profile charts
profile_images = [img for img in all_images if "_Profile" in img]

if not profile_images:
    print("No profile images found. Please check the base_folder path.")
    exit()

# -------------------------------------------------------------------------
# 2. GROUP IMAGES BY LOCATION
# -------------------------------------------------------------------------
location_suffix_pattern = re.compile(
    r"_(ADT|PBC|BikeGrouping|NearMiss|BikeSpeed|Parking|Speeds|Speed|Counts|Count)_Profile$",
    flags=re.IGNORECASE,
)

locations = {}

for img_path in profile_images:
    filename = os.path.basename(img_path).replace(".png", "")
    
    # Extract the location name by stripping the metric suffix
    loc_name = location_suffix_pattern.sub("", filename)
        
    # Clean up underscores for the document headers
    display_name = loc_name.replace("_", " ").strip()
    
    if display_name not in locations:
        locations[display_name] = []
    locations[display_name].append(img_path)

# -------------------------------------------------------------------------
# 3. BUILD THE WORD DOCUMENT
# -------------------------------------------------------------------------
doc = Document()
doc.add_heading('SAFR Project: Visual Profiles Appendix', 0)

# Sort locations alphabetically for a neat table of contents flow
for loc in sorted(locations.keys()):
    doc.add_heading(loc, level=1)
    
    # Sort the images within the location so they appear in a consistent order
    for img_path in sorted(locations[loc]):
        # Create a clean sub-heading for the specific metric
        metric_name = os.path.basename(img_path).replace(".png", "").replace("_", " ")
        doc.add_heading(metric_name, level=2)
        
        # Add the image and scale it to fit nicely on a standard Word page
        doc.add_picture(img_path, width=Inches(6.0))
        
        # Insert a page break so the next graph starts fresh on a new page
        doc.add_page_break()

# -------------------------------------------------------------------------
# 4. SAVE EXPORT
# -------------------------------------------------------------------------
output_path = output_file if os.path.isabs(output_file) else os.path.join(base_folder, output_file)
doc.save(output_path)

print(f"Successfully compiled {len(profile_images)} images into a Word Document!")
print(f"Saved to: {output_path}")
